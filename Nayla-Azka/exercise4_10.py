# Exercise 4-10: Slices
# Mengambil beberapa elemen dari daftar
pizzas = ["Pizza Pepperoni", "Pizza Keju", "Pizza Meat Lover", "Pizza Vegetarian", "Pizza BBQ"]

# Menampilkan tiga pizza pertama
print("Tiga pizza pertama:")
print(pizzas[:3])

# Menampilkan tiga pizza tengah
print("\nTiga pizza bagian tengah:")
print(pizzas[1:4])

# Menampilkan tiga pizza terakhir
print("\nTiga pizza terakhir:")
print(pizzas[-3:])