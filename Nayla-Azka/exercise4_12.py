# Exercise 4-12: More Loops
# Menampilkan dua daftar makanan menggunakan for loop

# Daftar makanan favorit saya
myFoods = ["Bakso", "Burger", "Pasta", "Sushi"]

# Daftar makanan favorit teman saya
friendFoods = ["Pizza", "Salad", "Gudeg", "Ramen"]

# Menampilkan daftar makanan favorit saya
print("Daftar makanan favorit saya:")
for food in myFoods:
    print(food)

# Menampilkan daftar makanan favorit teman saya
print("\nDaftar makanan favorit teman saya:")
for food in friendFoods:
    print(food)