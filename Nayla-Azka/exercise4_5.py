# Exercise 4-5: Summing a Million
# Membuat daftar angka dari 1 sampai 1.000.000
angka = list(range(1, 1000001))

# Menampilkan angka terkecil
print("Angka terkecil:", min(angka))

# Menampilkan angka terbesar
print("Angka terbesar:", max(angka))

# Menjumlahkan semua angka
print("Jumlah semua angka:", sum(angka))